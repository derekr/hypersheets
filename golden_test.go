// TestStructuralGoldenFullSheet is the same differential on the real fixture:
// 9,999 x 26, 220,382 cells, the sheet every number in DATA-MODEL.md was taken
// on. Skipped under -short because it seeds four full sheets.
func TestStructuralGoldenFullSheet(t *testing.T) {
	if testing.Short() {
		t.Skip("seeds a full sheet; skipped under -short")
	}
	for _, tc := range fullSheetGoldenCases {
		t.Run(tc.name, func(t *testing.T) {
			c := newTestCache(t, 4, time.Minute)
			sh := mustSeed(t, c, "goldenfull", goldenExtent-1, MaxCols)
			mustExtent(t, sh, goldenExtent)
			var err error
			if tc.del {
				_, err = sh.DeleteRows(tc.at, 1)
			} else {
				_, err = sh.InsertRows(tc.at, 1)
			}
			if err != nil {
				t.Fatalf("%s: %v", tc.name, err)
			}
			goldenCheck(t, tc.name, tc.hash, goldenDump(t, sh, fullGoldenWindows, goldenProbes))
		})
	}
}
