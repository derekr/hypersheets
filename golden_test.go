// TestStructuralGolden runs every mutation shape against a seeded sheet and
// checks the resulting sheet against a hash taken from the previous storage
// model. It is the regression net under the whole band-key promotion.
func TestStructuralGolden(t *testing.T) {
	for _, tc := range structuralGoldenCases {
		t.Run(tc.name, func(t *testing.T) {
			c := newTestCache(t, 4, time.Minute)
			sh := mustSeed(t, c, "golden", tc.rows, MaxCols)
			mustExtent(t, sh, goldenExtent)
			tc.apply(t, sh)
			goldenCheck(t, tc.name, tc.hash, goldenDump(t, sh, goldenWindows, goldenProbes))
		})
	}
}

